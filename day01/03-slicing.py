
nums = [10,20,30,40,50,60,70,80,90]
print(nums)
print(f"输出任意一个大于50的数字：{nums[5]}")
print(f"输出前三个的数字：{nums[0:3]}")
print(f"反转输出前三个的数字：{nums[0:3][::-1]}")
print(f"输出任意一串数字：{nums[3:6]}")
print(f"输出倒数第一个数字：{nums[-1]}")
print(f"输出倒数三个数字：{nums[-3:]}")
print(f"输出反转的集合：{nums[::-1]}")
print(f"反转输出倒数三个数字：{nums[-3:][::-1]}")